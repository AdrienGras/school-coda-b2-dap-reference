<?php

namespace App\Entity;

use ApiPlatform\Metadata\ApiResource;
use ApiPlatform\Metadata\Delete;
use ApiPlatform\Metadata\GetCollection;
use ApiPlatform\Metadata\Post;
use ApiPlatform\OpenApi\Model\Operation as OpenApiOperation;
use ApiPlatform\OpenApi\Model\Response as OpenApiResponse;
use App\Dto\Cart\CartAddLineInput;
use App\Dto\Cart\CartDetailsOutput;
use App\Entity\Enum\CartStatus;
use App\Entity\Impl\AbstractEntity;
use App\Repository\CartRepository;
use App\State\Cart\CartAddLineProcessor;
use App\State\Cart\CartCollectionProvider;
use App\State\Cart\CartOpenProcessor;
use App\State\Cart\CartProvider;
use App\State\Cart\CartRemoveLineProcessor;
use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\ORM\Mapping as ORM;
use Symfony\Bridge\Doctrine\Types\UuidType;
use Symfony\Component\Uid\Uuid;

#[ORM\Entity(repositoryClass: CartRepository::class)]
#[ApiResource(operations: [
    new Post(
        uriTemplate: '/carts',
        // le contrat n'envoie aucun corps sur cette adresse : il n'y a rien à désérialiser
        input: false,
        output: CartDetailsOutput::class,
        processor: CartOpenProcessor::class,
        // toutes les opérations du panier exigent un jeton, comme `/users/me` à l'étape 5
        security: "is_granted('ROLE_USER')",
    ),
    new GetCollection(
        uriTemplate: '/carts',
        output: CartDetailsOutput::class,
        provider: CartCollectionProvider::class,
        security: "is_granted('ROLE_USER')",
        // le générateur déduit la réponse du `output:`, qui nomme une classe et non un tableau :
        // il annonce un objet unique là où l'API rend une liste. On corrige la documentation,
        // sans toucher à `security:` : contrairement à la recherche de lancers, le cadenas dit vrai.
        openapi: new OpenApiOperation(
            responses: ['200' => new OpenApiResponse(
                description: 'Le panier en cours du porteur du jeton, ou aucun',
                content: new \ArrayObject(['application/json' => ['schema' => [
                    'type' => 'array',
                    // le nom généré du schéma, composé du shortName de la ressource et de la classe de sortie
                    'items' => ['$ref' => '#/components/schemas/Cart.CartDetailsOutput'],
                ]]]),
            )],
        ),
    ),
    new Post(
        uriTemplate: '/carts/{id}/items',
        input: CartAddLineInput::class,
        output: CartDetailsOutput::class,
        provider: CartProvider::class,
        processor: CartAddLineProcessor::class,
        security: "object.getCreatedBy() == user",
    ),
    new Delete(
        uriTemplate: '/carts/{id}/items/{itemId}',
        // ni input: ni output: — le contrat n'envoie aucun corps sur cette adresse et n'en
        // attend aucun ; le 204 vient du null que rend le processor
        provider: CartProvider::class,
        processor: CartRemoveLineProcessor::class,
        // la même expression que l'opération précédente, servie par le même provider : les deux
        // portent sur la même ressource, le panier
        security: "object.getCreatedBy() == user",
    ),
])]
class Cart extends AbstractEntity
{
    #[ORM\Id]
    #[ORM\Column(type: UuidType::NAME, unique: true)]
    private Uuid $id;

    #[ORM\Column(enumType: CartStatus::class)]
    private CartStatus $status = CartStatus::Pending;

    /**
     * @var Collection<int, CartItem>
     */
    #[ORM\OneToMany(
        mappedBy: 'cart',
        targetEntity: CartItem::class,
        cascade: ['persist'],
        orphanRemoval: false,
    )]
    private Collection $items;

    /**
     * Builds an empty pending cart with a time-ordered UUID, generated by the entity itself.
     */
    public function __construct()
    {
        $this->id = Uuid::v7();
        $this->items = new ArrayCollection();
    }

    public function getId(): Uuid
    {
        return $this->id;
    }

    public function getStatus(): CartStatus
    {
        return $this->status;
    }

    public function setStatus(CartStatus $status): static
    {
        $this->status = $status;

        return $this;
    }

    /**
     * @return Collection<int, CartItem>
     */
    public function getItems(): Collection
    {
        return $this->items;
    }

    /**
     * Attaches an item to this cart, and points the item back to it.
     */
    public function addItem(CartItem $item): static
    {
        $this->items->add($item);
        $item->setCart($this);

        return $this;
    }
}
